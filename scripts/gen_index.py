#!/usr/bin/env python3
"""Regenerate the games table in README.md from maps/*/*.json (stdlib only).

usage: python3 -I scripts/gen_index.py [--check]
The table lives between the BEGIN/END marker comments in README.md.
--check changes nothing and exits 1 if the README table is out of date.
"""
import json
import sys
from pathlib import Path

BEGIN = "<!-- BEGIN GAMES (generated by scripts/gen_index.py; do not edit) -->"
END = "<!-- END GAMES -->"
HEADER = ("| Platform | Game | Region | File | Status | Entries / coverage | ROM SHA-1 |\n"
          "|---|---|---|---|---|---|---|")
REGIONS = {"usa": "USA", "europe": "Europe", "japan": "Japan", "world": "World", "korea": "Korea",
           "australia": "Australia", "germany": "Germany", "france": "France", "spain": "Spain",
           "italy": "Italy"}


def counts(d):
    """Return (total entries, unconfirmed entries, coverage text)."""
    entries = []
    values = d.get("values", {})
    fields = [f for s in d.get("structs", {}).values() for f in s.get("fields", {}).values()]
    ents = d.get("entities", {})
    tables = d.get("rom_tables", {})
    for group in (values.values(), fields, ents.values(), tables.values()):
        entries.extend(group)
    flags = d.get("flags") or {}
    total = len(entries) + (1 if flags else 0)
    unconf = sum(1 for e in entries if e.get("status") == "unconfirmed")
    parts = ["%d values" % len(values), "%d struct fields" % len(fields), "%d entities" % len(ents)]
    if flags:
        parts.append("%d flags" % flags["bits"])
    parts.append("%d ROM tables" % len(tables))
    return total, unconf, "%d (%s)" % (total, ", ".join(parts))


def row(path, d):
    region = REGIONS.get(path.stem.rsplit("-", 1)[-1], path.stem.rsplit("-", 1)[-1])
    _, unconf, cov = counts(d)
    status = "confirmed" if not unconf else "%d unconfirmed" % unconf
    sha = d["rom"]["sha1"][0][:8]
    return "| %s | %s | %s | [%s](maps/%s/%s) | %s | %s | `%s` |" % (
        d["system"].upper(), d["game"], region, path.name, path.parent.name, path.name, status, cov, sha)


def table(root):
    rows = []
    for p in sorted(Path(root, "maps").glob("*/*.json")):
        with open(p, encoding="utf-8") as f:
            rows.append(((p.parent.name, p.name), row(p, json.load(f))))
    return "\n".join([HEADER] + [r for _, r in sorted(rows)])


def render(readme_text, root):
    a, b = readme_text.find(BEGIN), readme_text.find(END)
    if a < 0 or b < a:
        raise ValueError("README.md is missing the BEGIN/END marker comments")
    return readme_text[:a + len(BEGIN)] + "\n" + table(root) + "\n" + readme_text[b:]


def main(argv):
    root = Path(__file__).resolve().parent.parent
    readme = root / "README.md"
    old = readme.read_text(encoding="utf-8")
    try:
        new = render(old, root)
    except ValueError as e:
        print(e, file=sys.stderr)
        return 2
    if "--check" in argv:
        if new != old:
            print("README.md games table is out of date; run scripts/gen_index.py", file=sys.stderr)
            return 1
        print("README.md games table is up to date")
        return 0
    readme.write_text(new, encoding="utf-8")
    print("README.md updated")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
